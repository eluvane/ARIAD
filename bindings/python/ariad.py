"""Synchronous H2 bindings. Run native calls in workers outside async or UI threads.

Each call owns its input and output storage until the native function returns.
Independent stream and datagram directions may run concurrently. Native BUSY
is reported as an AriadError. No operation is retried by this module.
"""

