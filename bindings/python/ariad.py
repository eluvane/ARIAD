def _integer(value: int, minimum: int, maximum: int, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{name} must be an integer")
    if not minimum <= value <= maximum:
        raise ValueError(f"{name} must be in {minimum}..{maximum}")
    return int(value)


def _timeout(value: int) -> int:
    return _integer(value, 1, MAX_TIMEOUT_MS, "timeout_ms")


def _input(
    data: bytes | bytearray | memoryview,
    minimum: int,
    maximum: int,
) -> tuple[ctypes.Array[ctypes.c_uint8] | None, int]:
    if not isinstance(data, (bytes, bytearray, memoryview)):
        raise TypeError("data must be bytes, bytearray, or memoryview")
    size = data.nbytes if isinstance(data, memoryview) else len(data)
    if not minimum <= size <= maximum:
        raise ValueError(f"input length must be in {minimum}..{maximum}")
    data = bytes(data)
    buffer = (ctypes.c_uint8 * len(data)).from_buffer_copy(data) if data else None
    return buffer, len(data)


def _text(value: str, encoding: str) -> tuple[ctypes.Array[ctypes.c_uint8] | None, int]:
    if not isinstance(value, str):
        raise TypeError("text must be str")
    if "\x00" in value:
        raise ValueError("text must not contain NUL")
    if len(value) > MAX_TEXT:
        raise ValueError(f"text must contain at most {MAX_TEXT} bytes")
    return _input(value.encode(encoding), 1, MAX_TEXT)


class Library:
    """Load an explicit shared-library path and require ABI_VERSION."""

    def __init__(self, path: str | Path) -> None:
        self.path = Path(path).resolve(strict=True)
        self._native = ctypes.CDLL(str(self.path))
        version = self._native.ariad_abi_version
        version.argtypes, version.restype = _SIGNATURES["ariad_abi_version"]
        actual = version()
        if actual != ABI_VERSION:
            raise AbiVersionError(f"expected ABI {ABI_VERSION}, received {actual}")
        for name, (args, result) in _SIGNATURES.items():
            if name in ("ariad_abi_version", "ariad_status_name"):
                continue
            function = getattr(self._native, name)
            function.argtypes = args
            function.restype = result
        self._status_query = getattr(self._native, "ariad_status_name", None)
        if self._status_query is not None:
            self._status_query.argtypes, self._status_query.restype = _SIGNATURES[
                "ariad_status_name"
            ]

    def status_name(self, status: int) -> str:
        status = _integer(status, -(2**31), 2**31 - 1, "status")
        if self._status_query is not None:
            name = cast("bytes | None", self._status_query(status))
            if name is None:
                raise AbiContractError("ariad_status_name returned NULL")
            return name.decode("ascii")
        try:
            return "ARIAD_" + Status(status).name
        except ValueError:
            return "ARIAD_STATUS_UNKNOWN"

    def _check(
        self,
        operation: str,
        status: int,
        accepted: tuple[Status, ...] = (Status.OK,),
    ) -> Status:
        if status not in accepted:
            raise AriadError(operation, status, self.status_name(status))
        return Status(status)

    def create_engine(
        self,
        endpoint: str,
        identity: str,
        trust_root_der: bytes,
        *,
        cleanup_timeout_ms: int = 5000,
    ) -> Engine:
        cleanup_timeout_ms = _timeout(cleanup_timeout_ms)
        endpoint_buffer, endpoint_len = _text(endpoint, "utf-8")
        identity_buffer, identity_len = _text(identity, "ascii")
        root_buffer, root_len = _input(trust_root_der, 1, MAX_TRUST_ROOT_DER_BYTES)
        handle = _HANDLE()
        status = self._native.ariad_engine_create(
            endpoint_buffer,
            endpoint_len,
            identity_buffer,
            identity_len,
            root_buffer,
            root_len,
            ctypes.byref(handle),
        )
        self._check("ariad_engine_create", status)
        if handle.value == 0:
            raise AbiContractError("ariad_engine_create returned a zero handle")
        return Engine(self, handle.value, cleanup_timeout_ms=cleanup_timeout_ms)

    def protocol_version(self) -> int:
        return int(self._native.ariad_protocol_version())

    def h2_binding_version(self) -> int:
        return int(self._native.ariad_h2_binding_version())

    def supported(self, feature: Feature | int) -> bool | None:
        value = self._native.ariad_supported(_integer(feature, 0, 2**32 - 1, "feature"))
        if value not in (-1, 0, 1):
            raise AbiContractError("ariad_supported returned an unknown value")
        return None if value == -1 else bool(value)

    def wire_compatible(self, protocol: int, h2_binding: int) -> bool:
        value = self._native.ariad_wire_compatible(
            _integer(protocol, 0, 65535, "protocol"),
            _integer(h2_binding, 0, 65535, "h2_binding"),
        )
        if value not in (0, 1):
            raise AbiContractError("ariad_wire_compatible returned an unknown value")
        return bool(value)

    def target(self, target: Target | int) -> TargetClass | None:
        value = self._native.ariad_target(_integer(target, 0, 2**32 - 1, "target"))
        if value == -1:
            return None
        try:
            return TargetClass(value)
        except ValueError as error:
            raise AbiContractError("ariad_target returned an unknown value") from error


class _Handle(ABC):
    def __init__(self, library: Library, handle: int, parent: _Handle | None = None) -> None:
        self._library = library
        self._handle = _integer(handle, 1, 2**64 - 1, "handle")
        self._parent = parent
        self._root: _Handle = parent._root if parent is not None else self
        self._lock: RLock = parent._lock if parent is not None else RLock()
        self._parent_epoch = parent._epoch if parent is not None else 0
        # Epoch changes invalidate children without locks across native waits.
        self._epoch: int = 0
        self._usable = True
        self._open = True
        self._failed = False
        self.last_teardown_status: int | None = None
        self.last_cleanup_error: Exception | None = None

    def _valid(self) -> bool:
        return self._handle != 0 and (
            self._parent is None
            or (self._parent._valid() and self._parent_epoch == self._parent._epoch)
        )

    def _current(self, *, require_open: bool = False) -> tuple[int, int]:
        with self._lock:
            if not self._valid():
                raise HandleClosedError("handle or parent has been destroyed")
            if not self._usable or self._root._failed:
                raise HandleClosedError("handle is unusable; destroy its engine")
            if require_open and not self._open:
                raise HandleClosedError("handle has been closed or shut down")
            return self._handle, self._epoch

    def _check(
        self,
        operation: str,
        status: int,
        accepted: tuple[Status, ...] = (Status.OK,),
    ) -> Status:
        if status == Status.ERROR_INTERNAL:
            with self._lock:
                self._root._failed = True
                self._root._epoch += 1
        return self._library._check(operation, status, accepted)

    def _adopt(self, child_type: type[_HandleT], handle: int, epoch: int) -> _HandleT:
        with self._lock:
            if not self._valid() or self._epoch != epoch or not self._open:
                raise HandleClosedError("parent closed while opening child")
            if handle == 0:
                raise AbiContractError("successful open returned a zero handle")
            return child_type(self._library, handle, self)

    def _open_child(
        self, operation: str, child_type: type[_HandleT], *arguments: object
    ) -> _HandleT:
        current, epoch = self._current(require_open=True)
        handle = _HANDLE()
        status = getattr(self._library._native, operation)(
            current, *arguments, ctypes.byref(handle)
        )
        self._check(operation, status)
        return self._adopt(child_type, handle.value, epoch)

    def _destroy_handle(self) -> int:
        with self._lock:
            if not self._valid():
                self._handle = 0
                return 0
            return self._handle

    def _after_teardown(self, status: int, *, destroys: bool) -> None:
        with self._lock:
            self.last_teardown_status = status
            if status in (Status.ERROR_BUSY, Status.ERROR_INVALID_ARGUMENT):
                return
            self._epoch += 1
            self._open = False
            terminal = (
                Status.OK,
                Status.FORCED,
                Status.ERROR_TRANSPORT,
                Status.ERROR_INVALID_HANDLE,
            )
            if (destroys and status in terminal) or status == Status.ERROR_INVALID_HANDLE:
                self._handle = 0
            elif status not in terminal:
                # Retain an uncertain handle only for explicit teardown.
                self._usable = False

    def _destroy(
        self,
        operation: str,
        *arguments: object,
        accepted: tuple[Status, ...] = (Status.OK,),
    ) -> Status:
        handle = self._destroy_handle()
        if handle == 0:
            return Status.OK
        status = getattr(self._library._native, operation)(handle, *arguments)
        self._after_teardown(status, destroys=True)
        return self._check(operation, status, accepted)

    @abstractmethod
    def destroy(self) -> Status:
        raise NotImplementedError

    def __enter__(self: _HandleT) -> _HandleT:
        self._current()
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> Literal[False]:
        self.last_cleanup_error = None
        try:
            self.destroy()
        except Exception as error:
            self.last_cleanup_error = error
            if exc_value is None:
                raise
            add_note = getattr(BaseException, "add_note", None)
            if add_note is not None:
                # Keep the body error even if its note storage is invalid.
                with suppress(Exception):
                    add_note(exc_value, f"ARIAD context cleanup failed: {error}")
        return False


class Engine(_Handle):
    """Own one native runtime. Context exit uses the configured cleanup deadline."""

    def __init__(self, library: Library, handle: int, *, cleanup_timeout_ms: int) -> None:
        super().__init__(library, handle)
        self.cleanup_timeout_ms = _timeout(cleanup_timeout_ms)

    def connect(self, credential: bytes, *, timeout_ms: int = 5000) -> Session:
        timeout_ms = _timeout(timeout_ms)
        buffer, length = _input(credential, CREDENTIAL_BYTES, CREDENTIAL_BYTES)
        return self._open_child("ariad_engine_connect", Session, buffer, length, timeout_ms)

    def shutdown(self, *, timeout_ms: int = 5000) -> Status:
        timeout_ms = _timeout(timeout_ms)
        handle, _ = self._current()
        status = self._library._native.ariad_engine_shutdown(handle, timeout_ms)
        self._after_teardown(status, destroys=False)
        return self._check("ariad_engine_shutdown", status, (Status.OK, Status.FORCED))

    def destroy(self, *, timeout_ms: int | None = None) -> Status:
        timeout_ms = _timeout(self.cleanup_timeout_ms if timeout_ms is None else timeout_ms)
        return self._destroy(
            "ariad_engine_destroy", timeout_ms, accepted=(Status.OK, Status.FORCED)
        )


class Session(_Handle):
    """Own a connection. close invalidates flows; destroy releases the handle."""

    def open_stream(self, destination: str, *, timeout_ms: int = 5000) -> Stream:
        timeout_ms = _timeout(timeout_ms)
        buffer, length = _text(destination, "ascii")
        return self._open_child("ariad_session_open_stream", Stream, buffer, length, timeout_ms)

    def open_datagram(
        self,
        destination: str,
        *,
        require_unreliable: bool = False,
        timeout_ms: int = 5000,
    ) -> Association:
        timeout_ms = _timeout(timeout_ms)
        if not isinstance(require_unreliable, bool):
            raise TypeError("require_unreliable must be bool")
        buffer, length = _text(destination, "ascii")
        return self._open_child(
            "ariad_session_open_datagram",
            Association,
            buffer,
            length,
            int(require_unreliable),
            timeout_ms,
        )

    def close(
        self,
        mode: CloseMode = CloseMode.GRACEFUL,
        *,
        timeout_ms: int = 5000,
    ) -> Status:
        timeout_ms = _timeout(timeout_ms)
        mode = CloseMode(_integer(mode, 0, 1, "mode"))
        handle, _ = self._current()
        status = self._library._native.ariad_session_close(handle, int(mode), timeout_ms)
        self._after_teardown(status, destroys=False)
        return self._check("ariad_session_close", status, (Status.OK, Status.FORCED))

    def destroy(self) -> Status:
        return self._destroy("ariad_session_destroy")


class Stream(_Handle):
    """Write accepted prefixes. Read nonempty prefixes, or b'' only for clean EOF."""

    def write(self, data: bytes, *, timeout_ms: int = 5000) -> int:
        timeout_ms = _timeout(timeout_ms)
        buffer, length = _input(data, 1, MAX_COPY)
        handle, _ = self._current()
        written = _SIZE()
        status = self._library._native.ariad_stream_write(
            handle,
            buffer,
            length,
            timeout_ms,
            ctypes.byref(written),
        )
        self._check("ariad_stream_write", status)
        if not 1 <= written.value <= length:
            raise AbiContractError("successful write returned an invalid count")
        return written.value

    def read(self, capacity: int = MAX_COPY, *, timeout_ms: int = 5000) -> bytes:
        timeout_ms = _timeout(timeout_ms)
        capacity = _integer(capacity, 1, MAX_COPY, "capacity")
        handle, _ = self._current()
        buffer = (ctypes.c_uint8 * capacity)()
        count = _SIZE()
        status = self._library._native.ariad_stream_read(
            handle,
            buffer,
            capacity,
            timeout_ms,
            ctypes.byref(count),
        )
        self._check("ariad_stream_read", status, (Status.OK, Status.EOF))
        if status == Status.EOF:
            if count.value != 0:
                raise AbiContractError("EOF returned a nonzero count")
            return b""
        if not 1 <= count.value <= capacity:
            raise AbiContractError("successful read returned an invalid count")
        return bytes(buffer[: count.value])

    def end_write(self, *, timeout_ms: int = 5000) -> None:
        timeout_ms = _timeout(timeout_ms)
        handle, _ = self._current()
        self._check(
            "ariad_stream_end_write",
            self._library._native.ariad_stream_end_write(handle, timeout_ms),
        )

    def cancel(self) -> None:
        handle, _ = self._current()
        self._check("ariad_stream_cancel", self._library._native.ariad_stream_cancel(handle))

    def reset(self) -> None:
        handle, _ = self._current()
        self._check("ariad_stream_reset", self._library._native.ariad_stream_reset(handle))

    def destroy(self) -> Status:
        return self._destroy("ariad_stream_destroy")


class Association(_Handle):
    """Send and receive whole datagrams. An empty receive is a message, not EOF."""

    def delivery_mode(self) -> DeliveryMode:
        handle, _ = self._current()
        mode = _U32()
        status = self._library._native.ariad_association_delivery_mode(handle, ctypes.byref(mode))
        self._check("ariad_association_delivery_mode", status)
        try:
            return DeliveryMode(mode.value)
        except ValueError as error:
            raise AbiContractError("unknown delivery mode") from error

    def max_payload(self) -> int:
        handle, _ = self._current()
        size = _SIZE()
        status = self._library._native.ariad_association_max_payload(handle, ctypes.byref(size))
        self._check("ariad_association_max_payload", status)
        if size.value > MAX_COPY:
            raise AbiContractError("max_payload exceeds the ABI limit")
        return size.value

    def send(self, data: bytes, *, timeout_ms: int = 5000) -> Status:
        timeout_ms = _timeout(timeout_ms)
        buffer, length = _input(data, 0, MAX_COPY)
        handle, _ = self._current(require_open=True)
        status = self._library._native.ariad_association_send(handle, buffer, length, timeout_ms)
        return self._check("ariad_association_send", status, (Status.OK, Status.DROPPED))

    def recv(self, capacity: int = MAX_COPY, *, timeout_ms: int = 5000) -> bytes:
        timeout_ms = _timeout(timeout_ms)
        capacity = _integer(capacity, 0, MAX_COPY, "capacity")
        handle, _ = self._current(require_open=True)
        buffer = (ctypes.c_uint8 * capacity)() if capacity else None
        count = _SIZE()
        status = self._library._native.ariad_association_recv(
            handle,
            buffer,
            capacity,
            timeout_ms,
            ctypes.byref(count),
        )
        self._check("ariad_association_recv", status)
        if count.value > capacity:
            raise AbiContractError("successful recv returned an invalid count")
        return bytes(buffer[: count.value]) if buffer is not None else b""

    def close(self) -> None:
        handle, _ = self._current()
        status = self._library._native.ariad_association_close(handle)
        self._after_teardown(status, destroys=False)
        self._check("ariad_association_close", status)

    def destroy(self) -> Status:
        return self._destroy("ariad_association_destroy")
